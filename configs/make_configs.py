"""Generate configs/<setting>/<model>_s<N>.yaml from settings.yaml and models.yaml.

    python configs/make_configs.py                    # every setting
    python configs/make_configs.py main honeypot      # just these
    python configs/make_configs.py --check            # regenerate in memory, compare to disk

Precedence: models.yaml[model].defaults < settings[setting].config < the setting's
per-model ``overrides`` (an override of ``null`` removes the key). Every other key of a
models.yaml entry (``model``, ``ignore_providers``, ``reasoning_enabled``) is copied in
first, so a setting can still override it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Dict, Iterator, Tuple

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
FIXTURES = "trilemma/fixtures"

#: Run-control keys first, then the prompt switches, then the texts — so a config reads top
#: down. Keys not listed keep their settings.yaml order after these.
ORDER = ["setting", "name", "seed", "model", "reasoning_enabled", "ignore_providers",
         "fixture", "script", "confidentiality", "discussion_norms", "dm_hint2",
         "calendar_rule", "honesty_norm", "wake_batching", "warmup_start", "preask_at",
         "ask_at_overrides", "converge_on", "horizon", "debrief_at", "clock_scale",
         "slot_seconds", "temperature", "turn_timeout", "max_turns", "max_wall_seconds",
         "ask", "ask_overrides", "debrief", "extra_assistants"]


def load() -> Tuple[Dict[str, Any], Dict[str, Any]]:
    models = yaml.safe_load((HERE / "models.yaml").read_text())
    settings = yaml.safe_load((HERE / "settings.yaml").read_text())["settings"]
    return models, settings


def build(setting: str, spec: Dict[str, Any], model: str, entry: Dict[str, Any],
          seed: int) -> Dict[str, Any]:
    cfg: Dict[str, Any] = {k: v for k, v in entry.items() if k != "defaults"}
    cfg.update(entry.get("defaults") or {})
    cfg.update(spec.get("config") or {})
    for k, v in ((spec["models"][model] or {}).get("overrides") or {}).items():
        if v is None:
            cfg.pop(k, None)
        else:
            cfg[k] = v
    cfg["fixture"] = f"{FIXTURES}/{spec['world']}.json"
    cfg.update(setting=setting, name=f"{model}_s{seed}", seed=seed)
    ordered = {k: cfg[k] for k in ORDER if k in cfg}
    ordered.update({k: v for k, v in cfg.items() if k not in ordered})
    return ordered


def configs(only: Tuple[str, ...] = ()) -> Iterator[Tuple[Path, Dict[str, Any]]]:
    models, settings = load()
    for setting, spec in settings.items():
        if only and setting not in only:
            continue
        for model, m in spec["models"].items():
            if model not in models:
                raise SystemExit(f"{setting}: model {model!r} is not in models.yaml")
            for seed in m["seeds"]:
                yield (HERE / setting / f"{model}_s{seed}.yaml",
                       build(setting, spec, model, models[model], int(seed)))


def dump(cfg: Dict[str, Any]) -> str:
    head = (f"# {cfg['setting']} / {cfg['name']} — generated by configs/make_configs.py from "
            f"settings.yaml; edit that, not this file.\n")
    return head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=100)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("settings", nargs="*", help="limit to these settings")
    ap.add_argument("--check", action="store_true", help="compare against the files on disk")
    args = ap.parse_args()
    n = bad = 0
    for path, cfg in configs(tuple(args.settings)):
        text = dump(cfg)
        n += 1
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad += 1
                print(f"DIFFERS {path.relative_to(REPO)}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"{n} configs {'checked' if args.check else 'written'}"
          + (f", {bad} differ" if args.check else ""))
    if bad:
        sys.exit(1)


if __name__ == "__main__":
    main()
